// Regenerate configopts.h from the real config.json, so the fixture cannot drift
// from what the configuration page actually offers. Run before building the C tests.
var fs = require('fs');
var SRC = require('path').join(process.argv[2] ||
    require('path').resolve(__dirname, '..', '..'), 'src');
var cfg = JSON.parse(fs.readFileSync(SRC + '/pkjs/config.json'));

function itemFor(key) {
    var found = null;
    (function walk(items) {
        items.forEach(function(it) {
            if (it.messageKey === key) { found = it; }
            if (it.items) { walk(it.items); }
        });
    })(cfg);
    if (!found) { throw new Error('config.json has no item for ' + key); }
    return found;
}
function selectLines(key, name) {
    var it = itemFor(key);
    var values = it.options.map(function(o) { return parseInt(o.value, 10); });
    return 'static const int32_t ' + name + '[] = {' + values.join(', ') + '};\n' +
           'static const int32_t ' + name + '_DEFAULT = ' + parseInt(it.defaultValue, 10) + ';\n';
}
function colorLine(key, name) {
    var it = itemFor(key);
    return '#define ' + name + ' 0x' + String(it.defaultValue).replace(/^#/, '').toUpperCase() + '\n';
}

// Every item on the page with a message key is a tuple in the dictionary the watch receives
function pageSettings() {
    var count = 0;
    (function walk(items) {
        items.forEach(function(it) {
            if (it.messageKey) { count++; }
            if (it.items) { walk(it.items); }
        });
    })(cfg);
    return count;
}

// Coarse mode's accents with their bands, and the accent each of the 64 colors becomes, from the
// one table jstest.js also holds the configuration page to
function paletteLines() {
    var palettes = JSON.parse(fs.readFileSync(require('path').join(__dirname, 'palettes.json')));
    var hex = function(h) { return '0x' + h.toUpperCase(); };
    var out = 'static const uint32_t COARSE_PAIRS_FIXTURE[][2] = {\n';
    palettes.pairs.forEach(function(pair) {
        out += '    {' + hex(pair[0]) + ', ' + hex(pair[1]) + '},\n';
    });
    out += '};\nstatic const uint32_t COARSE_MOVES_FIXTURE[][2] = {\n';
    Object.keys(palettes.coarse).forEach(function(from) {
        out += '    {' + hex(from) + ', ' + hex(palettes.coarse[from]) + '},\n';
    });
    return out + '};\n';
}

var out = '// generated by gen_configopts.js from src/pkjs/config.json\n' +
          '// do not edit; run `node gen_configopts.js` instead\n\n' +
          selectLines('tenSecondUpdatesAbove', 'TEN_OPTS') +
          selectLines('minuteUpdatesAbove', 'MIN_OPTS') +
          selectLines('instantStart', 'CFG_INSTANT_START') +
          colorLine('timerColor', 'TIMER_COLOR_DEFAULT') +
          colorLine('chronoColor', 'CHRONO_COLOR_DEFAULT') +
          '#define CFG_OVERRUN_CHRONO_DEFAULT ' + (itemFor('overrunChrono').defaultValue ? 1 : 0) + '\n' +
          '#define CFG_PAGE_SETTINGS ' + pageSettings() + '\n' +
          paletteLines();
fs.writeFileSync('configopts.h', out);
process.stdout.write(out);
